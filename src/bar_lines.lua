function B.shuffleBag(list, rng)
  local out = {}
  local n = #(list or {})
  for i = 1, n do out[i] = list[i] end
  for i = n, 2, -1 do
    local j
    if rng then
      j = rng(1, i)
    else
      j = math.random(1, i)
    end
    if type(j) ~= 'number' then j = i end
    j = math.floor(j)
    if j < 1 then j = 1 elseif j > i then j = i end
    out[i], out[j] = out[j], out[i]
  end
  return out
end

