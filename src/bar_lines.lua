-- 洗牌袋内部状态：bag 存 1..COUNT 的乱序下标，bagPos 指向下一个待取位置
local bag = {}
local bagPos = 1
-- 专属科普袋（与通用袋独立）：triviaBag 存当前周期的文案，triviaBagPos 指向下一个待取
local triviaBag = {}
local triviaBagPos = 1

-- 清空袋子（下次 next 时重新洗）；专属科普袋一并清空，保证新开局从干净周期开始
function BarLines.resetBag()
    bag = {}
    bagPos = 1
    triviaBag = {}
    triviaBagPos = 1
end

-- 洗一袋新下标（Fisher-Yates，从后往前 swap）
local function reshuffle()
    bag = {}
    for i = 1, BarLines.COUNT do
        bag[i] = i
    end
    for i = #bag, 2, -1 do
        local j = love.math.random(i)
        bag[i], bag[j] = bag[j], bag[i]
    end
    bagPos = 1
end

-- 取一条文案并推进袋子；袋子空了自动重新洗一袋
function BarLines.next()
    if bagPos > #bag then
        reshuffle()
    end
    local idx = bag[bagPos]
    bagPos = bagPos + 1
    return BarLines.LINES[idx]
end

-- 当前袋子里还剩几条
function BarLines.bagRemaining()
    local remaining = #bag - bagPos + 1
    if remaining < 0 then remaining = 0 end
    return remaining
end

-- ============================================================
-- 专属科普入口：按「当前已有的酒 id 列表」取科普
--   ids = state.bar.cups 的酒 id 与 state.bar.buffs 生效酒 key 的并集（调用方拼好传入）
--   规则：ids 非空时约一半概率从专属池取（独立洗牌袋，周期内不重复），
--         其余与空表 / nil / 全部无效 id 时回退到通用池 BarLines.next()。
--   随机只用 love.math.random；通用池沿用既有袋子，不额外消耗随机数（ids 为空
--   时与 next() 的随机序列完全一致）。
-- ============================================================
local function triviaPool(ids)
    local flat = {}
    if type(ids) ~= "table" then return flat end
    for _, id in ipairs(ids) do
        local t = type(id) == "string" and BarLines.TRIVIA[id] or nil
        if type(t) == "table" then
            for _, line in ipairs(t) do
                if type(line) == "string" and #line > 0 then flat[#flat + 1] = line end
            end
        end
    end
    return flat
end

function BarLines.nextTrivia(ids)
    local flat = triviaPool(ids)
    if #flat > 0 and love.math.random() < 0.5 then
        if triviaBagPos > #triviaBag then
            triviaBag = flat
            for i = #triviaBag, 2, -1 do
                local j = love.math.random(i)
                triviaBag[i], triviaBag[j] = triviaBag[j], triviaBag[i]
            end
            triviaBagPos = 1
        end
        local line = triviaBag[triviaBagPos]
        triviaBagPos = triviaBagPos + 1
        return line
    end
    return BarLines.next()
end

return BarLines